use crate::{
    indexer::Indexer,
    key::TxKey,
    lock_guards::LockGuards,
    lock_policies::lock_policy::LockPolicy,
    new_types::{BitMask, HashCode, MAX_SHARDS, ShardCount, ShardIndex},
    shard::Shard,
    shard_map::{MaskGuard, ShardMap},
};
use hashbrown::HashTable;
use std::hash::{BuildHasher, Hash};

/// Internal store of the map's shards.
///
/// Backed by a [`ShardMap`]: a fixed array of leaf slots plus a lock-free
/// routing trie and the atomic masks used by the transaction lock protocol.
/// Splits and merges only change routing, never leaf storage, so a leaf's
/// address is stable for the lifetime of the map.
///
/// Exposed so the prepared transaction types generated by
/// [`tx_schema`](macro@crate::tx_schema) can be defined outside this crate.
#[doc(hidden)]
pub struct Custodian<K, V, L>
where
    L: LockPolicy,
{
    pub(crate) map: ShardMap<L::Lock<Shard<K, V>>>,
}

impl<K, V, L> Custodian<K, V, L>
where
    L: LockPolicy,
{
    pub(crate) fn new(shard_count: ShardCount, capacity: usize) -> Self {
        let budget = shard_count.0 as u32;
        let per_leaf = capacity.div_ceil(budget.max(1) as usize);
        let mut custodian = Self {
            map: ShardMap::new(L::new(HashTable::with_capacity(per_leaf)), budget),
        };
        custodian.presplit(per_leaf);
        custodian
    }

    /// Builds a fresh custodian whose active leaves are exactly `shards`, in
    /// active-id order.
    pub(crate) fn from_shards(shard_count: ShardCount, shards: Vec<Shard<K, V>>) -> Self {
        let custodian = Self::new(shard_count, 0);
        let ids = custodian.map.active_ids();
        debug_assert_eq!(ids.len(), shards.len());
        for (id, shard) in ids.into_iter().zip(shards) {
            // SAFETY: construction has exclusive access; the slot is active
            // and initialised.
            unsafe {
                let slot = custodian.map.leaf_mut(id);
                *slot = L::new(shard);
            }
        }
        custodian
    }

    /// Grows the trie from a single leaf up to the configured budget.
    ///
    /// Every split replaces one leaf with eight children (reusing the source
    /// leaf id and reserving seven fresh ids). The resulting leaf count is the
    /// largest `1 + 7k` that does not exceed the budget.
    fn presplit(&mut self, per_leaf: usize) {
        let mut frontier = vec![0u8];
        while self.map.leaf_count() + 7 <= self.map.budget() {
            let mut next = Vec::new();
            for leaf in frontier {
                if self.map.leaf_count() + 7 > self.map.budget() {
                    next.push(leaf);
                    continue;
                }
                let Some(ids) = self.map.allocate_ids(7) else {
                    next.push(leaf);
                    continue;
                };
                let mut children = [0u8; 8];
                children[0] = leaf;
                children[1..].copy_from_slice(&ids[..7]);
                for &id in &ids[..7] {
                    // SAFETY: `id` was just reserved and is uniquely owned.
                    unsafe {
                        self.map
                            .init_leaf(id, L::new(HashTable::with_capacity(per_leaf)))
                    };
                }
                if self.map.routing.split_leaf(leaf, children).is_some() {
                    next.extend_from_slice(&children);
                } else {
                    for &id in &ids[..7] {
                        // SAFETY: roll back the freshly initialised slots.
                        unsafe { drop(self.map.take_leaf(id)) };
                    }
                    next.push(leaf);
                }
            }
            frontier = next;
        }
    }

    /// Routes a hash code to a leaf.
    #[doc(hidden)]
    #[inline]
    pub fn route(&self, hash_code: HashCode) -> ShardIndex {
        ShardIndex(self.map.route(hash_code.0))
    }

    /// Current version of a leaf.
    #[doc(hidden)]
    #[inline]
    pub fn version(&self, shard_index: ShardIndex) -> u32 {
        self.map.version(shard_index.0)
    }

    /// Hashes and routes `key`, capturing the leaf's current version.
    pub(crate) fn indexed_key<S>(&self, indexer: &Indexer<S>, key: K) -> TxKey<K>
    where
        K: Hash,
        S: BuildHasher,
    {
        let hash_code = indexer.hash(&key);
        let shard_index = self.route(hash_code);
        TxKey {
            hash_code,
            shard_index,
            version: self.map.version(shard_index.0),
            key,
        }
    }

    /// Snapshot of the active leaf ids.
    pub(crate) fn active_ids(&self) -> Vec<u8> {
        self.map.active_ids()
    }

    /// Number of active leaves.
    pub(crate) fn active_count(&self) -> usize {
        self.map.leaf_count() as usize
    }

    /// Acquires every active leaf and returns a guard releasing them on drop.
    pub(crate) fn acquire_all(&self) -> MaskGuard<'_, L::Lock<Shard<K, V>>> {
        self.map.acquire_all_guard()
    }

    /// Acquires the given read/write masks and checks the expected versions.
    ///
    /// All leaves are acquired in one all-or-nothing atomic operation before
    /// any version is checked, which is what keeps the protocol deadlock-free.
    #[doc(hidden)]
    pub fn try_lock_guards(
        &self,
        read: BitMask,
        write: BitMask,
        versions: &[(u8, u32)],
    ) -> Option<LockGuards<'_, K, V, L>> {
        let needed = read.0 | write.0;
        let mask = self.map.acquire_guard(needed);
        if versions
            .iter()
            .any(|&(id, version)| self.map.version(id) != version)
        {
            return None;
        }
        Some(self.build_lock_guards(read, write, mask))
    }

    /// Acquires read/write guards for the given shard bitmasks.
    pub fn lock_guards(&self, read: BitMask, write: BitMask) -> LockGuards<'_, K, V, L> {
        self.try_lock_guards(read, write, &[])
            .expect("empty version list never fails")
    }

    fn build_lock_guards<'a>(
        &'a self,
        read: BitMask,
        write: BitMask,
        mask: MaskGuard<'a, L::Lock<Shard<K, V>>>,
    ) -> LockGuards<'a, K, V, L> {
        let mut read_guards = std::array::from_fn(|_| None);
        let mut write_guards = std::array::from_fn(|_| None);

        let mut bits = read.0 | write.0;
        while bits != 0 {
            let i = bits.trailing_zeros() as usize;
            bits &= bits - 1;
            let bit = BitMask(1u128 << i);
            // SAFETY: `mask` holds leaf `i`, so the slot is initialised and
            // exclusively accessible to this transaction.
            let shard_lock = unsafe { self.map.leaf_ref(i as u8) };
            if (write & bit) != BitMask::ZERO {
                write_guards[i] = Some(L::write(shard_lock));
            } else {
                read_guards[i] = Some(L::read(shard_lock));
            }
        }
        LockGuards {
            read: read_guards,
            write: write_guards,
            write_bitmask: write,
            _mask: mask,
        }
    }

    /// Acquires write guards for the given shard bitmask.
    ///
    /// The returned mask guard must be kept alive for as long as the write
    /// guards are used.
    #[allow(clippy::type_complexity)]
    pub(crate) fn write_guards(
        &self,
        write: BitMask,
    ) -> (
        [Option<L::WriteGuard<'_, Shard<K, V>>>; MAX_SHARDS],
        MaskGuard<'_, L::Lock<Shard<K, V>>>,
    ) {
        let mask = self.map.acquire_guard(write.0);
        let mut write_guards = std::array::from_fn(|_| None);
        let mut bits = write.0;
        while bits != 0 {
            let i = bits.trailing_zeros() as usize;
            bits &= bits - 1;
            // SAFETY: `mask` holds leaf `i`.
            let shard_lock = unsafe { self.map.leaf_ref(i as u8) };
            write_guards[i] = Some(L::write(shard_lock));
        }
        (write_guards, mask)
    }

    pub(crate) fn read_guard_at(&self, shard_index: ShardIndex) -> L::ReadGuard<'_, Shard<K, V>> {
        // SAFETY: `shard_index` is an active leaf. Single-key operations do
        // not change routing, so the leaf cannot disappear underneath them.
        let shard_lock = unsafe { self.map.leaf_ref(shard_index.0) };
        L::read(shard_lock)
    }

    pub(crate) fn write_guard_at(&self, shard_index: ShardIndex) -> L::WriteGuard<'_, Shard<K, V>> {
        // SAFETY: see `read_guard_at`.
        let shard_lock = unsafe { self.map.leaf_ref(shard_index.0) };
        L::write(shard_lock)
    }
}
