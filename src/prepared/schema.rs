use crate::{hasher::DefaultBuildHasher, indexer::Indexer, new_types::ShardCount};
use std::hash::BuildHasher;

/// Schema trait for a prepared transaction.
///
/// Associates every type a prepared transaction needs (key, value, lock
/// policy, hasher, keys, params, state) with the schema type. Implemented
/// by the [`tx_schema`] macro. Because all of these types are associated
/// types, a [`PreparedTransaction`](crate::prepared::transaction::PreparedTransaction)
/// only needs the schema as a generic parameter.
pub trait TxSchema {
    /// The key type of the map the transaction operates on.
    type Key;
    /// The value type of the map the transaction operates on.
    type Value;
    /// The raw (un-indexed) keys type.
    type Keys: TxKeys<Self::Key, Self::IndexedKeys, Self::Hasher>;
    /// The indexed keys type after hashing.
    type IndexedKeys;
    /// The parameters passed on each execution.
    type Params;
    /// The mutable working state (must be `Default`).
    type State: Default;
    /// The lock policy of the map the transaction operates on.
    type LockPolicy: crate::lock_policies::lock_policy::LockPolicy;
    /// The hasher of the map the transaction operates on.
    type Hasher: BuildHasher;
}

/// Raw keys that can be hashed into indexed keys.
pub trait TxKeys<K, IndexedKeys, S = DefaultBuildHasher>
where
    S: BuildHasher,
{
    /// Converts raw keys to indexed keys by computing hashes and shard indices.
    fn into_indexed(self, shard_count: ShardCount, indexer: &Indexer<S>) -> IndexedKeys;
}

/// Selects a single key from a set of indexed keys.
///
/// Implemented by key handle types generated by [`tx_schema`].
pub trait TxKeySelector<K, KEYS> {
    /// Returns a reference to the selected key.
    fn get<'keys>(&self, keys: &'keys KEYS) -> &'keys K;
    /// Returns a stable identifier for the selected key handle.
    ///
    /// Used at transaction build time to detect whether a key handle is seen
    /// by a later operation. When the final op to reference a handle is a
    /// consuming operation, the handle is "provably last-used", so its key
    /// can be moved instead of cloned.
    fn key_id(&self) -> &'static str;
    /// Takes the selected key out of the keys container.
    ///
    /// Only safe to call when the handle is provably last-used within the
    /// transaction (see [`key_id`](TxKeySelector::key_id)).
    fn take(&self, keys: &mut KEYS) -> K;
}

#[macro_export]
macro_rules! tx_schema {
    // `value` only: lock policy and hasher default to `MutexPolicy` and
    // `DefaultBuildHasher`.
    (
        $name:ident,
        keys: [ $($key:ident),* $(,)? ],
        params: { $($param_field:ident: $param_type:ty),* $(,)? },
        state: { $($state_field:ident: $state_type:ty),* $(,)? },
        value: $value:ty $(,)?
    ) => {
        $crate::tx_schema! {
            @impl $name,
            keys: [ $($key),* ],
            params: { $($param_field: $param_type),* },
            state: { $($state_field: $state_type),* },
            value: $value,
            lock_policy: $crate::lock_policies::mutex_policy::MutexPolicy,
            hasher: $crate::hasher::DefaultBuildHasher,
        }
    };
    // `lock_policy` only.
    (
        $name:ident,
        keys: [ $($key:ident),* $(,)? ],
        params: { $($param_field:ident: $param_type:ty),* $(,)? },
        state: { $($state_field:ident: $state_type:ty),* $(,)? },
        value: $value:ty,
        lock_policy: $lock_policy:ty $(,)?
    ) => {
        $crate::tx_schema! {
            @impl $name,
            keys: [ $($key),* ],
            params: { $($param_field: $param_type),* },
            state: { $($state_field: $state_type),* },
            value: $value,
            lock_policy: $lock_policy,
            hasher: $crate::hasher::DefaultBuildHasher,
        }
    };
    // `hasher` only.
    (
        $name:ident,
        keys: [ $($key:ident),* $(,)? ],
        params: { $($param_field:ident: $param_type:ty),* $(,)? },
        state: { $($state_field:ident: $state_type:ty),* $(,)? },
        value: $value:ty,
        hasher: $hasher:ty $(,)?
    ) => {
        $crate::tx_schema! {
            @impl $name,
            keys: [ $($key),* ],
            params: { $($param_field: $param_type),* },
            state: { $($state_field: $state_type),* },
            value: $value,
            lock_policy: $crate::lock_policies::mutex_policy::MutexPolicy,
            hasher: $hasher,
        }
    };
    // Both `lock_policy` and `hasher`.
    (
        $name:ident,
        keys: [ $($key:ident),* $(,)? ],
        params: { $($param_field:ident: $param_type:ty),* $(,)? },
        state: { $($state_field:ident: $state_type:ty),* $(,)? },
        value: $value:ty,
        lock_policy: $lock_policy:ty,
        hasher: $hasher:ty $(,)?
    ) => {
        $crate::tx_schema! {
            @impl $name,
            keys: [ $($key),* ],
            params: { $($param_field: $param_type),* },
            state: { $($state_field: $state_type),* },
            value: $value,
            lock_policy: $lock_policy,
            hasher: $hasher,
        }
    };
    (
        @impl $name:ident,
        keys: [ $($key:ident),* $(,)? ],
        params: { $($param_field:ident: $param_type:ty),* $(,)? },
        state: { $($state_field:ident: $state_type:ty),* $(,)? },
        value: $value:ty,
        lock_policy: $lock_policy:ty,
        hasher: $hasher:ty $(,)?
    ) => {
        $crate::_paste! {
            pub use [<__private $name>] :: $name;
            pub use [<__private $name>] :: [<$name Keys>];
            pub use [<__private $name>] :: [<$name Params>];
            pub use [<__private $name>] :: [<$name State>];
            #[allow(non_snake_case)]
            mod [<__private $name>] {
                // Bring the types referenced by the macro invocation (value,
                // params, state, lock_policy, hasher) into scope of this
                // private module.
                #[allow(unused_imports)]
                use super::*;
                #[allow(unused_imports)]
                use $crate::prelude::*;

                // schema
                pub struct $name<K> {
                    _phantom: std::marker::PhantomData<K>,
                }
                impl<K> $crate::prelude::TxSchema for $name<K>
                where
                    K: std::hash::Hash,
                {
                    type Key = K;
                    type Value = $value;
                    type Keys =   [<$name Keys>]<K>;
                    type IndexedKeys = [<$name IndexedKeys>]<K>;
                    type Params = [<$name Params>];
                    type State =  [<$name State>];
                    type LockPolicy = $lock_policy;
                    type Hasher = $hasher;
                }
                impl<K> $name<K> {
                    pub const SCHEMA: $name<K> = $name {
                        _phantom: std::marker::PhantomData,
                    };
                    $(
                        #[allow(non_upper_case_globals)]
                        pub const $key: [<$name _ $key>]<K> = [<$name _ $key>] {
                            _phantom: std::marker::PhantomData,
                        };
                    )*
                }

                // keys
                pub struct [<$name Keys>]<K> {
                    $(pub $key: K,)*
                }

                // params
                pub struct [<$name Params>] {
                    $(pub $param_field: $param_type,)*
                }

                // state
                #[derive(Debug, Default, Hash, PartialEq, Eq)]
                pub struct [<$name State>] {
                    $(pub $state_field: $state_type,)*
                }

                pub struct [<$name IndexedKeys>]<K> {
                    $(pub $key: std::option::Option<$crate::prelude::TxKey<K>>,)*
                }
                $(
                    #[allow(non_camel_case_types)]
                    pub struct [<$name _ $key>]<K> {
                    _phantom: std::marker::PhantomData<K>,
                    }
                )*
                $(
                    impl<K> $crate::prelude::TxKeySelector<$crate::prelude::TxKey<K>, [<$name IndexedKeys>]<K>> for [<$name _ $key>]<K>
                    {
                        fn get<'keys>(&self, keys: &'keys [<$name IndexedKeys>]<K>) -> &'keys $crate::prelude::TxKey<K> {
                            keys.$key.as_ref().expect("key handle already consumed")
                        }
                        fn key_id(&self) -> &'static str {
                            stringify!($key)
                        }
                        fn take(&self, keys: &mut [<$name IndexedKeys>]<K>) -> $crate::prelude::TxKey<K> {
                            keys.$key.take().expect("key handle already consumed")
                        }
                    }
                )*
                impl<K, S> $crate::prelude::TxKeys<K, [<$name IndexedKeys>]<K>, S> for [<$name Keys>]<K>
                where
                    K: std::hash::Hash,
                    S: std::hash::BuildHasher,
                {
                    fn into_indexed(self, shard_count: $crate::prelude::ShardCount, indexer: &$crate::indexer::Indexer<S>) -> [<$name IndexedKeys>]<K> {
                        [<$name IndexedKeys>] {
                            $(
                                $key: std::option::Option::Some(indexer.indexed_key(shard_count, self.$key)),
                            )*
                        }
                    }
                }
            }
        }
    };
}

pub use tx_schema;
