use crate::{
    hasher::DefaultBuildHasher,
    indexer::Indexer,
    lock_policies::lock_policy::LockPolicy,
    new_types::ShardCount,
    prepared::tx_builder::{
        PreparedTxBuilder, PreparedTxOperationsBuilder, PreparedTxRequirementsBuilder,
    },
    tx_map::TxMap,
};
use std::hash::BuildHasher;

/// Schema trait for a prepared transaction.
///
/// Associates keys, parameters, and state types with a transaction.
/// Implemented by the [`tx_schema`] macro.
pub trait TxSchema<K> {
    /// The raw (un-indexed) keys type.
    type Keys: TxKeys<K, Self::IndexedKeys>;
    /// The indexed keys type after hashing.
    type IndexedKeys;
    /// The parameters passed on each execution.
    type Params;
    /// The mutable working state (must be `Default`).
    type State: Default;

    /// The schema's builder while it is still accepting guard requirements,
    /// generated by [`tx_schema`].
    ///
    /// The builder accumulates guards and operations for the schema's
    /// transaction. It implements
    /// [`PreparedTxRequirementsBuilder`] and
    /// [`PreparedTxOperationsBuilder`].
    type Builder<'tx, V, L, S>: PreparedTxRequirementsBuilder<'tx, K, V, L, S, Self::IndexedKeys, Self::Params, Self::State>
        + PreparedTxOperationsBuilder<'tx, K, V, L, S, Self::IndexedKeys, Self::Params, Self::State>
    where
        Self: 'tx,
        K: 'tx,
        V: 'tx,
        L: LockPolicy + 'tx,
        S: BuildHasher + 'tx,
        Self::IndexedKeys: 'tx,
        Self::Params: 'tx,
        Self::State: 'tx;

    /// The schema's builder once it has at least one operation, generated by
    /// [`tx_schema`].
    ///
    /// It implements [`PreparedTxOperationsBuilder`] and
    /// [`PreparedTxBuilder`].
    type Buildable<'tx, V, L, S>: PreparedTxOperationsBuilder<'tx, K, V, L, S, Self::IndexedKeys, Self::Params, Self::State>
        + PreparedTxBuilder<'tx, K, V, L, S, Self::IndexedKeys, Self::Params, Self::State>
    where
        Self: 'tx,
        K: 'tx,
        V: 'tx,
        L: LockPolicy + 'tx,
        S: BuildHasher + 'tx,
        Self::IndexedKeys: 'tx,
        Self::Params: 'tx,
        Self::State: 'tx;

    /// The schema's transaction type, generated by [`tx_schema`].
    type Tx<'tx, V, L, S>
    where
        Self: 'tx,
        K: 'tx,
        V: 'tx,
        L: LockPolicy + 'tx,
        S: BuildHasher + 'tx;

    /// Starts building a prepared transaction for this schema on the given
    /// map.
    ///
    /// Every type is inferred from the map, so no generic parameters need to
    /// be written. [`TxMap::prepared_tx`](crate::tx_map::TxMap::prepared_tx)
    /// delegates to this method.
    fn builder<'tx, V, L, S>(&self, map: &'tx TxMap<K, V, L, S>) -> Self::Builder<'tx, V, L, S>
    where
        Self: Sized + 'tx,
        K: 'tx,
        V: 'tx,
        L: LockPolicy + 'tx,
        S: BuildHasher + 'tx,
        Self::IndexedKeys: 'tx,
        Self::Params: 'tx,
        Self::State: 'tx;
}

/// Raw keys that can be hashed into indexed keys.
pub trait TxKeys<K, IndexedKeys, S = DefaultBuildHasher>
where
    S: BuildHasher,
{
    /// Converts raw keys to indexed keys by computing hashes and shard indices.
    fn into_indexed(self, shard_count: ShardCount, indexer: &Indexer<S>) -> IndexedKeys;
}

/// Selects a single key from a set of indexed keys.
///
/// Implemented by key handle types generated by [`tx_schema`].
pub trait TxKeySelector<K, KEYS> {
    /// Returns a reference to the selected key.
    fn get<'keys>(&self, keys: &'keys KEYS) -> &'keys K;
    /// Returns a stable identifier for the selected key handle.
    ///
    /// Used at transaction build time to detect whether a key handle is seen
    /// by a later operation. When the final op to reference a handle is a
    /// consuming operation, the handle is "provably last-used", so its key
    /// can be moved instead of cloned.
    fn key_id(&self) -> &'static str;
    /// Takes the selected key out of the keys container.
    ///
    /// Only safe to call when the handle is provably last-used within the
    /// transaction (see [`key_id`](TxKeySelector::key_id)).
    fn take(&self, keys: &mut KEYS) -> K;
}

#[macro_export]
macro_rules! tx_schema {
    (
        $name:ident,
        keys: [ $($key:ident),* $(,)? ],
        params: { $($param_field:ident: $param_type:ty),* $(,)? },
        state: { $($state_field:ident: $state_type:ty),* $(,)? }
        $(,)?
    ) => {
        $crate::_paste! {
            pub use [<__private $name>] :: $name;
            pub use [<__private $name>] :: [<$name Keys>];
            pub use [<__private $name>] :: [<$name Params>];
            pub use [<__private $name>] :: [<$name State>];
            pub use [<__private $name>] :: [<$name Builder>];
            pub use [<__private $name>] :: [<$name Buildable>];
            pub use [<__private $name>] :: [<$name Tx>];
            #[allow(non_snake_case)]
            mod [<__private $name>] {
                // schema
                pub struct $name<K> {
                    _phantom: std::marker::PhantomData<K>,
                }
                impl<K> $crate::TxSchema<K> for $name<K>
                where
                    K: std::hash::Hash,
                {
                    type Keys =   [<$name Keys>]<K>;
                    type IndexedKeys = [<$name IndexedKeys>]<K>;
                    type Params = [<$name Params>];
                    type State =  [<$name State>];

                    type Builder<'tx, V, L, S> = [<$name Builder>]<'tx, K, V, L, S>
                    where
                        Self: 'tx,
                        K: 'tx,
                        V: 'tx,
                        L: $crate::LockPolicy + 'tx,
                        S: std::hash::BuildHasher + 'tx,
                        Self::IndexedKeys: 'tx,
                        Self::Params: 'tx,
                        Self::State: 'tx;

                    type Buildable<'tx, V, L, S> = [<$name Buildable>]<'tx, K, V, L, S>
                    where
                        Self: 'tx,
                        K: 'tx,
                        V: 'tx,
                        L: $crate::LockPolicy + 'tx,
                        S: std::hash::BuildHasher + 'tx,
                        Self::IndexedKeys: 'tx,
                        Self::Params: 'tx,
                        Self::State: 'tx;

                    type Tx<'tx, V, L, S> = [<$name Tx>]<'tx, K, V, L, S>
                    where
                        Self: 'tx,
                        K: 'tx,
                        V: 'tx,
                        L: $crate::LockPolicy + 'tx,
                        S: std::hash::BuildHasher + 'tx;

                    fn builder<'tx, V, L, S>(
                        &self,
                        map: &'tx $crate::TxMap<K, V, L, S>,
                    ) -> [<$name Builder>]<'tx, K, V, L, S>
                    where
                        K: 'tx,
                        V: 'tx,
                        L: $crate::LockPolicy + 'tx,
                        S: std::hash::BuildHasher + 'tx,
                        Self::IndexedKeys: 'tx,
                        Self::Params: 'tx,
                        Self::State: 'tx,
                    {
                        [<$name Builder>] {
                            custodian: &map.custodian,
                            indexer: &map.indexer,
                            guards: std::vec::Vec::new(),
                        }
                    }
                }
                impl<K> $name<K> {
                    pub const SCHEMA: $name<K> = $name {
                        _phantom: std::marker::PhantomData,
                    };
                    $(
                        #[allow(non_upper_case_globals)]
                        pub const $key: [<$name _ $key>]<K> = [<$name _ $key>] {
                            _phantom: std::marker::PhantomData,
                        };
                    )*
                }

                // keys
                pub struct [<$name Keys>]<K> {
                    $(pub $key: K,)*
                }

                // params
                pub struct [<$name Params>] {
                    $(pub $param_field: $param_type,)*
                }

                // state
                #[derive(Debug, Default, Hash, PartialEq, Eq)]
                pub struct [<$name State>] {
                    $(pub $state_field: $state_type,)*
                }

                pub struct [<$name IndexedKeys>]<K> {
                    $(pub $key: std::option::Option<$crate::TxKey<K>>,)*
                }
                $(
                    #[allow(non_camel_case_types)]
                    pub struct [<$name _ $key>]<K> {
                    _phantom: std::marker::PhantomData<K>,
                    }
                )*
                $(
                    impl<K> $crate::TxKeySelector<$crate::TxKey<K>, [<$name IndexedKeys>]<K>> for [<$name _ $key>]<K>
                    {
                        fn get<'keys>(&self, keys: &'keys [<$name IndexedKeys>]<K>) -> &'keys $crate::TxKey<K> {
                            keys.$key.as_ref().expect("key handle already consumed")
                        }
                        fn key_id(&self) -> &'static str {
                            stringify!($key)
                        }
                        fn take(&self, keys: &mut [<$name IndexedKeys>]<K>) -> $crate::TxKey<K> {
                            keys.$key.take().expect("key handle already consumed")
                        }
                    }
                )*
                impl<K, S> $crate::TxKeys<K, [<$name IndexedKeys>]<K>, S> for [<$name Keys>]<K>
                where
                    K: std::hash::Hash,
                    S: std::hash::BuildHasher,
                {
                    fn into_indexed(self, shard_count: $crate::ShardCount, indexer: &$crate::indexer::Indexer<S>) -> [<$name IndexedKeys>]<K> {
                        [<$name IndexedKeys>] {
                            $(
                                $key: std::option::Option::Some(indexer.indexed_key(shard_count, self.$key)),
                            )*
                        }
                    }
                }

                // builder (accepts guards and operations)
                pub struct [<$name Builder>]<'tx, K, V, L, S>
                where
                    K: 'tx,
                    V: 'tx,
                    L: $crate::LockPolicy + 'tx,
                    S: std::hash::BuildHasher + 'tx,
                {
                    pub(crate) custodian: &'tx $crate::custodian::Custodian<K, V, L>,
                    pub(crate) indexer: &'tx $crate::indexer::Indexer<S>,
                    pub(crate) guards: std::vec::Vec<$crate::prepared::guard::Guard<'tx, K, V, [<$name IndexedKeys>]<K>, [<$name Params>], [<$name State>]>>,
                }

                impl<'tx, K, V, L, S>
                    $crate::prepared::tx_builder::PreparedTxRequirementsBuilder<
                        'tx,
                        K,
                        V,
                        L,
                        S,
                        [<$name IndexedKeys>]<K>,
                        [<$name Params>],
                        [<$name State>],
                    > for [<$name Builder>]<'tx, K, V, L, S>
                where
                    K: 'tx,
                    V: 'tx,
                    L: $crate::LockPolicy + 'tx,
                    S: std::hash::BuildHasher + 'tx,
                {
                    type Builder = [<$name Builder>]<'tx, K, V, L, S>;

                    fn with_guard(
                        mut self,
                        guard: $crate::prepared::guard::Guard<'tx, K, V, [<$name IndexedKeys>]<K>, [<$name Params>], [<$name State>]>,
                    ) -> Self::Builder {
                        self.guards.push(guard);
                        self
                    }
                }

                impl<'tx, K, V, L, S>
                    $crate::prepared::tx_builder::PreparedTxOperationsBuilder<
                        'tx,
                        K,
                        V,
                        L,
                        S,
                        [<$name IndexedKeys>]<K>,
                        [<$name Params>],
                        [<$name State>],
                    > for [<$name Builder>]<'tx, K, V, L, S>
                where
                    K: 'tx,
                    V: 'tx,
                    L: $crate::LockPolicy + 'tx,
                    S: std::hash::BuildHasher + 'tx,
                {
                    type Builder = [<$name Buildable>]<'tx, K, V, L, S>;

                    fn with_operation(
                        self,
                        op: $crate::prepared::op::PreparedOp<'tx, K, V, [<$name IndexedKeys>]<K>, [<$name Params>], [<$name State>]>,
                    ) -> Self::Builder {
                        [<$name Buildable>] {
                            custodian: self.custodian,
                            indexer: self.indexer,
                            guards: std::cell::Cell::new(self.guards),
                            ops: std::cell::Cell::new(std::vec![op]),
                        }
                    }
                }

                // buildable (accepts operations and can be turned into a tx)
                pub struct [<$name Buildable>]<'tx, K, V, L, S>
                where
                    K: 'tx,
                    V: 'tx,
                    L: $crate::LockPolicy + 'tx,
                    S: std::hash::BuildHasher + 'tx,
                {
                    pub(crate) custodian: &'tx $crate::custodian::Custodian<K, V, L>,
                    pub(crate) indexer: &'tx $crate::indexer::Indexer<S>,
                    pub(crate) guards: std::cell::Cell<std::vec::Vec<$crate::prepared::guard::Guard<'tx, K, V, [<$name IndexedKeys>]<K>, [<$name Params>], [<$name State>]>>>,
                    pub(crate) ops: std::cell::Cell<std::vec::Vec<$crate::prepared::op::PreparedOp<'tx, K, V, [<$name IndexedKeys>]<K>, [<$name Params>], [<$name State>]>>>,
                }

                impl<'tx, K, V, L, S>
                    $crate::prepared::tx_builder::PreparedTxOperationsBuilder<
                        'tx,
                        K,
                        V,
                        L,
                        S,
                        [<$name IndexedKeys>]<K>,
                        [<$name Params>],
                        [<$name State>],
                    > for [<$name Buildable>]<'tx, K, V, L, S>
                where
                    K: 'tx,
                    V: 'tx,
                    L: $crate::LockPolicy + 'tx,
                    S: std::hash::BuildHasher + 'tx,
                {
                    type Builder = [<$name Buildable>]<'tx, K, V, L, S>;

                    fn with_operation(
                        mut self,
                        op: $crate::prepared::op::PreparedOp<'tx, K, V, [<$name IndexedKeys>]<K>, [<$name Params>], [<$name State>]>,
                    ) -> Self::Builder {
                        self.ops.get_mut().push(op);
                        self
                    }
                }

                impl<'tx, K, V, L, S>
                    $crate::prepared::tx_builder::PreparedTxBuilder<
                        'tx,
                        K,
                        V,
                        L,
                        S,
                        [<$name IndexedKeys>]<K>,
                        [<$name Params>],
                        [<$name State>],
                    > for [<$name Buildable>]<'tx, K, V, L, S>
                where
                    K: 'tx,
                    V: 'tx,
                    L: $crate::LockPolicy + 'tx,
                    S: std::hash::BuildHasher + 'tx,
                {
                    type Tx = [<$name Tx>]<'tx, K, V, L, S>;

                    fn guards(&self) -> std::vec::Vec<$crate::prepared::guard::Guard<'tx, K, V, [<$name IndexedKeys>]<K>, [<$name Params>], [<$name State>]>> {
                        self.guards.take()
                    }
                    fn ops(&self) -> std::vec::Vec<$crate::prepared::op::PreparedOp<'tx, K, V, [<$name IndexedKeys>]<K>, [<$name Params>], [<$name State>]>> {
                        self.ops.take()
                    }
                    fn tx(
                        self,
                        guards: std::vec::Vec<$crate::prepared::guard::Guard<'tx, K, V, [<$name IndexedKeys>]<K>, [<$name Params>], [<$name State>]>>,
                        ops: std::vec::Vec<$crate::prepared::op::PreparedOp<'tx, K, V, [<$name IndexedKeys>]<K>, [<$name Params>], [<$name State>]>>,
                    ) -> Self::Tx {
                        [<$name Tx>] {
                            custodian: self.custodian,
                            indexer: self.indexer,
                            guards,
                            ops,
                        }
                    }
                }

                // tx (the prepared transaction)
                pub struct [<$name Tx>]<'tx, K, V, L, S>
                where
                    K: 'tx,
                    V: 'tx,
                    L: $crate::LockPolicy + 'tx,
                    S: std::hash::BuildHasher + 'tx,
                {
                    pub(crate) custodian: &'tx $crate::custodian::Custodian<K, V, L>,
                    pub(crate) indexer: &'tx $crate::indexer::Indexer<S>,
                    pub(crate) guards: std::vec::Vec<$crate::prepared::guard::Guard<'tx, K, V, [<$name IndexedKeys>]<K>, [<$name Params>], [<$name State>]>>,
                    pub(crate) ops: std::vec::Vec<$crate::prepared::op::PreparedOp<'tx, K, V, [<$name IndexedKeys>]<K>, [<$name Params>], [<$name State>]>>,
                }

                impl<'tx, K, V, L, S> [<$name Tx>]<'tx, K, V, L, S>
                where
                    K: 'tx + std::clone::Clone + std::hash::Hash + std::cmp::Eq,
                    V: 'tx,
                    L: $crate::LockPolicy + 'tx,
                    S: std::hash::BuildHasher + 'tx,
                {
                    #[must_use]
                    /// Executes the transaction with the given keys and parameters.
                    ///
                    /// The keys are hashed, locks are acquired, guards are
                    /// checked, and operations are applied. Returns the final
                    /// state wrapped in
                    /// [`TxResult`](crate::TxResult).
                    pub fn execute(
                        &self,
                        keys: impl $crate::TxKeys<K, [<$name IndexedKeys>]<K>, S>,
                        params: [<$name Params>],
                    ) -> $crate::TxResult<[<$name State>]>
                    {
                        let mut indexed_keys = keys.into_indexed(self.custodian.shard_count, self.indexer);
                        let mut total_read_bitmask = $crate::new_types::BitMask::ZERO;
                        let mut total_write_bitmask = $crate::new_types::BitMask::ZERO;

                        // get all bitmasks
                        for guard in self.guards.iter() {
                            total_read_bitmask |= guard.read_bitmask(&indexed_keys);
                        }
                        for op in self.ops.iter() {
                            let (read_bitmask, write_bitmask) = op.read_write_bitmasks(&indexed_keys);
                            total_read_bitmask |= read_bitmask;
                            total_write_bitmask |= write_bitmask;
                        }
                        // ensure locks are either read or write, not both
                        total_read_bitmask &= !total_write_bitmask;

                        let mut lock_guards = self
                            .custodian
                            .lock_guards(total_read_bitmask, total_write_bitmask);
                        let mut state = [<$name State>]::default();
                        for (index, guard) in self.guards.iter().enumerate() {
                            if !guard.is_condition_met::<L>(&mut lock_guards, &indexed_keys, &params, &mut state)
                            {
                                return $crate::TxResult::RequirementNotMet {
                                    index,
                                    requirement: guard.name.clone(),
                                    state,
                                };
                            }
                        }
                        for op in self.ops.iter() {
                            op.apply::<L, S>(
                                &mut lock_guards,
                                &mut indexed_keys,
                                &params,
                                self.indexer,
                                &mut state,
                            );
                        }
                        $crate::TxResult::Completed { state }
                    }
                }
            }
        }
    };
}

pub use tx_schema;
